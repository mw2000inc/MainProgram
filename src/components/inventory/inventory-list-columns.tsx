// Otherwise a pure history/view — no add/delete/approve affordances anywhere
// on it (see the Daily Report panel wiring, which passes neither canAdd nor
// canDelete). Approving a movement stays exactly where it already was, on
// Inventory > In & Out — only editing (onEdit, inventory:edit-gated) was
// added here, so a wrong quantity/reason can be fixed without leaving the
// Daily Report page.

// 'pending'/'approved'/'rejected' (see the stock_movement_rejection
// migration) are the three real statuses this app has (see
// ApprovalStatusBadge on the In & Out page) — matches that badge's tones
// exactly so a movement reads the same way in both places.
// A requested edit/delete of an approved movement shows as "Edit pending" /
// "Delete pending" until it's approved or rejected.
export function InventoryStatusBadge({ status, change }: { status: StockMovementRow["status"]; change?: StockMovementRow["changeRequest"] }) {
  const { t } = useTranslation("status")
  if (change) return <StatusBadge tone="warning" label={change.action === "delete" ? "Delete pending" : "Edit pending"} />
  if (status === "pending") return <StatusBadge tone="warning" label={t("pending")} />
  if (status === "rejected") return <StatusBadge tone="danger" label={t("rejected")} />
  return <StatusBadge tone="success" label={t("approved")} />
}

// A "Manual" tag next to the reason, so an admin-typed entry (Restock/
// Return/Damaged/Adjustment) reads as clearly distinct from one a trigger
// wrote (Sale/Filter Change/Repair) at a glance — those already read as
// self-evidently system-generated by their reason text alone, so nothing is
// added there to avoid cluttering every row with a redundant tag. Same
// treatment as the In & Out Summary's own stock-movements-columns.tsx.
// The type box ticked for an item on the Release Slip, spelled out.
const SLIP_TYPE_LABEL: Record<string, string> = { F: "F · Filter Change", R: "R · Repair", S: "S · Installation", O: "O · Other" }
const slipTypeLabel = (t: string) => SLIP_TYPE_LABEL[t] ?? t

function ReasonCell({ row }: { row: StockMovementRow }) {
  const { t } = useTranslation("inventory")
  return (
    <span className="inline-flex items-center gap-1.5">
      {row.reason}
      {row.source === "Manual" && <StatusBadge tone="neutral" label={t("manualEntry")} />}
      {row.slipType && <StatusBadge tone="warning" label={slipTypeLabel(row.slipType)} />}
      {row.purpose && <StatusBadge tone="secondary" label={`For: ${row.purpose}`} />}
    </span>
  )
}

// Approve / Reject on a pending row, right in the Inventory List — approving
// applies the stock change at once (the database's approval trigger takes it
// OUT for fitted filters/parts/units, back IN for returned parts). A row
// combining several movements acts on all of them. A row not yet mapped to
// a stock item (an install model / hand-typed part) can't be approved until
// it is, so it offers Map item instead, which opens the review queue.
export function ApprovalActionsCell({
  movement,
  onApprove,
  onReject,
  onMap,
}: {
  movement: StockMovementRow
  onApprove: (movement: StockMovementRow) => void
  onReject: (movement: StockMovementRow) => void
  onMap: (movement: StockMovementRow) => void
}) {
  const { t } = useTranslation("inventory")
  const { t: tCommon } = useTranslation("common")
  if (!isAwaitingStockApproval(movement)) return null
  const stop = (fn: () => void) => (e: React.MouseEvent) => {
    e.stopPropagation()
    fn()
  }
  return (
    <div className="flex items-center gap-1">
      {movement.productId ? (
        <Button size="sm" className="h-7 gap-1 px-2" onClick={stop(() => onApprove(movement))}>
          <Check className="h-3.5 w-3.5" /> {tCommon("approve")}
        </Button>
      ) : (
        <Button size="sm" variant="outline" className="h-7 gap-1 px-2" onClick={stop(() => onMap(movement))}>
          <Link2 className="h-3.5 w-3.5" /> {t("mapItem")}
        </Button>
      )}
      <Button
        size="sm"
        variant="ghost"
        className="h-7 w-7 p-0 text-danger"
        aria-label={tCommon("reject")}
        title={tCommon("reject")}
        onClick={stop(() => onReject(movement))}
      >
        <X className="h-3.5 w-3.5" />
      </Button>
    </div>
  )
}

function EditButtonCell({
  movement,
  onEdit,
  className,
}: {
  movement: StockMovementRow
  onEdit: (movement: StockMovementRow) => void
  className?: string
}) {
  const { t } = useTranslation("common")
  return (
    <Button
      size="sm"
      variant="ghost"
      className={className}
      aria-label={t("edit")}
      onClick={(e) => {
        e.stopPropagation()
        onEdit(movement)
      }}
    >
      <Pencil className="h-4 w-4" />
    </Button>
  )
}

// A row's quantity counts every pool it moves: Brand New (quantityAdded /
// quantityRemoved) plus 2nd Hand (Ready), 2nd Hand (Repair) and Demo — those
// three are stored signed (negative = taken out; see AddMovementForm). A row
// is (almost) always entirely on one side; it falls back to showing both
// if a row genuinely has both, rather than silently dropping one.
type QtyRow = Pick<StockMovementRow, "quantityAdded" | "quantityRemoved" | "secondHandReadyQuantity" | "secondHandRepairQuantity" | "demoQuantity">
const conditionNet = (row: QtyRow) => (row.secondHandReadyQuantity || 0) + (row.secondHandRepairQuantity || 0) + (row.demoQuantity || 0)
function movementTypeAndQty(row: QtyRow): { type: "add" | "deduct" | "addDeduct"; qty: number } {
  const extra = conditionNet(row)
  const added = (row.quantityAdded || 0) + Math.max(extra, 0)
  const removed = (row.quantityRemoved || 0) + Math.max(-extra, 0)
  if (added > 0 && removed > 0) return { type: "addDeduct", qty: added - removed }
  if (removed > 0) return { type: "deduct", qty: removed }
  return { type: "add", qty: added }
}
const directionOf = (row: QtyRow) => (movementTypeAndQty(row).type === "deduct" ? "out" : "in")

// Which pools a row moves, when it isn't only Brand New ("2nd Hand (Ready) 5").
function ConditionNote({ row }: { row: QtyRow }) {
  const { t } = useTranslation("inventory")
  const parts = (
    [
      [t("brandNew"), (row.quantityAdded || 0) - (row.quantityRemoved || 0)],
      [t("secondHandReady"), row.secondHandReadyQuantity || 0],
      [t("secondHandRepair"), row.secondHandRepairQuantity || 0],
      [t("demo"), row.demoQuantity || 0],
    ] as const
  ).filter(([, n]) => n !== 0)
  if (!conditionNet(row) || parts.length === 0) return null
  return <span className="block text-xs font-normal text-muted-foreground" data-testid="inventory-condition">{parts.map(([label, n]) => `${label} ${Math.abs(n)}`).join(" · ")}</span>
}

const TYPE_KEYS = { add: "typeAdd", deduct: "typeDeduct", addDeduct: "typeAddDeduct" } as const

function TypeCell({ row }: { row: StockMovementRow }) {
  const { t } = useTranslation("inventory")
  const { type } = movementTypeAndQty(row)
  return <span className={type === "deduct" ? "text-danger" : "text-success"}>{t(TYPE_KEYS[type])}</span>
}

// The new quantity a requested edit would give (shown "-1 → -3").
function requestedQty(row: StockMovementRow): string | undefined {
  const v = row.changeRequest?.action === "edit" ? row.changeRequest.values : undefined
  if (!v) return undefined
  const { type, qty } = movementTypeAndQty({ ...row, quantityAdded: v.quantityAdded ?? row.quantityAdded, quantityRemoved: v.quantityRemoved ?? row.quantityRemoved })
  return type === "deduct" ? `-${qty}` : `+${qty}`
}

function QtyCell({ row }: { row: StockMovementRow }) {
  const { type, qty } = movementTypeAndQty(row)
  const shown = type === "deduct" ? `-${qty}` : `+${qty}`
  const next = requestedQty(row)
  if (row.changeRequest?.action === "delete") return <span className="font-medium line-through">{shown}</span>
  if (next !== undefined && next !== shown)
    return (
      <span className="font-medium whitespace-nowrap">
        <span className="text-muted-foreground line-through">{shown}</span> → <span className="text-warning">{next}</span>
      </span>
    )
  return (
    <span className="font-medium">
      {shown}
      <ConditionNote row={row} />
    </span>
  )
}

// The Daily Report panel's full column set — shown directly in the compact
// panel (horizontally scrollable, see daily-report-section.tsx's own
// tableClassName="min-w-max") as well as the Maximize2 dialog, which
// renders these exact same columns now that there's no narrower compact
// set held back from it.
//
// onEdit omitted (a technician, or an admin without inventory:edit) falls
// back to the plain column set with no trailing Edit column at all — same
// on/off convention every other Daily Report column set already uses for
// its own admin-only affordances.
// How much of the Inventory List fits the panel's width (see
// inventoryListDensityForWidth): "full" every column; "medium" drops
// Created By / Approved By / Time; "compact" folds Type, Quantity, Reason
// and Status under the item name and puts Edit beside Approve, leaving
// Item | Related Job | actions — so a narrow panel never scrolls sideways.
export type InventoryListDensity = "full" | "medium" | "compact"

export function inventoryListDensityForWidth(width: number): InventoryListDensity {
  if (width >= 1180) return "full"
  if (width >= 760) return "medium"
  return "compact"
}

function CompactItemCell({ row }: { row: StockMovementRow }) {
  const { t } = useTranslation("inventory")
  const { type } = movementTypeAndQty(row)
  return (
    <div className="min-w-0 max-w-[16rem]">
      <div className="truncate font-medium" title={row.productName}>
        {row.productName}
      </div>
      <div className="mt-0.5 flex flex-wrap items-center gap-x-1.5 gap-y-0.5 text-xs text-muted-foreground">
        <span className={type === "deduct" ? "text-danger" : "text-success"}>{t(TYPE_KEYS[type])}</span>
        <QtyCell row={row} />
        <span>· {row.reason}</span>
        {row.slipType && <span>· {slipTypeLabel(row.slipType)}</span>}
        {row.purpose && <span>· For: {row.purpose}</span>}
        {/* Who added it — the full view has a Created By column; here it's
            folded in so a technician's slip entry is easy to spot. */}
        {row.userName && <span>· by {row.userName}</span>}
        <InventoryStatusBadge status={row.status} change={row.changeRequest} />
      </div>
    </div>
  )
}

export function getInventoryListExpandedColumns({
  onEdit,
  onApprove,
  onReject,
  onMap,
  density = "full",
  showDate = false,
}: {
  density?: InventoryListDensity
  // A leading Date column — for lists that span several days (the
  // "Approve all dates" review of every pending item).
  showDate?: boolean
  onEdit?: (movement: StockMovementRow) => void
  // Admin-only approval actions on pending rows (see ApprovalActionsCell);
  // omitted, there's no Approve column.
  onApprove?: (movement: StockMovementRow) => void
  onReject?: (movement: StockMovementRow) => void
  onMap?: (movement: StockMovementRow) => void
} = {}): ColumnDef<StockMovementRow, unknown>[] {
  const actionsCell = (movement: StockMovementRow) => (
    <div className="flex items-center gap-1">
      {onApprove && onReject && onMap && <ApprovalActionsCell movement={movement} onApprove={onApprove} onReject={onReject} onMap={onMap} />}
      {onEdit && <EditButtonCell movement={movement} onEdit={onEdit} className="h-7 w-7 p-0" />}
    </div>
  )
  const dateColumns: ColumnDef<StockMovementRow, unknown>[] = showDate
    ? [{ accessorKey: "date", header: () => <ColumnHeader tKey="date" ns="inventory" />, cell: ({ row }) => <span className="whitespace-nowrap">{formatDate(row.original.date)}</span> }]
    : []
  if (density === "compact") {
    return [
      ...dateColumns,
      { accessorKey: "productName", header: () => <ColumnHeader tKey="item" ns="inventory" />, cell: ({ row }) => <CompactItemCell row={row.original} /> },
      {
        accessorKey: "relatedJobOrderNo",
        header: () => <ColumnHeader tKey="relatedJob" ns="inventory" />,
        cell: ({ row }) => (
          <span className="block max-w-[8rem] truncate" title={row.original.relatedJobOrderNo}>
            {row.original.relatedJobOrderNo || "—"}
          </span>
        ),
      },
      ...(onApprove || onEdit ? [{ id: "actions", header: "", cell: ({ row }) => actionsCell(row.original) } as ColumnDef<StockMovementRow, unknown>] : []),
    ]
  }

  const columns: ColumnDef<StockMovementRow, unknown>[] = [
    ...dateColumns,
    {
      accessorKey: "productName",
      header: () => <ColumnHeader tKey="item" ns="inventory" />,
      cell: ({ row }) => (
        <span className={cn("block truncate", density === "medium" ? "max-w-[14rem]" : "max-w-[22rem]")} title={row.original.productName}>
          {row.original.productName}
        </span>
      ),
    },
    { id: "type", header: () => <ColumnHeader tKey="type" ns="inventory" />, cell: ({ row }) => <TypeCell row={row.original} /> },
    { id: "qty", header: () => <ColumnHeader tKey="quantity" ns="fields" />, cell: ({ row }) => <QtyCell row={row.original} /> },
    {
      accessorKey: "reason",
      header: () => <ColumnHeader tKey="reason" ns="inventory" />,
      cell: ({ row }) => <ReasonCell row={row.original} />,
    },
    {
      accessorKey: "relatedJobOrderNo",
      header: () => <ColumnHeader tKey="relatedJob" ns="inventory" />,
      // A per-item total (aggregateInventoryRowsByItem) lists every order.
      cell: ({ row }) => <span className="block max-w-[18rem] whitespace-normal">{row.original.relatedJobOrderNo || "—"}</span>,
    },
    {
      accessorKey: "status",
      header: () => <ColumnHeader tKey="status" ns="fields" />,
      cell: ({ row }) => <InventoryStatusBadge status={row.original.status} change={row.original.changeRequest} />,
    },
    ...(density === "medium" ? [] : [
    { accessorKey: "userName", header: () => <ColumnHeader tKey="createdBy" ns="inventory" /> } as ColumnDef<StockMovementRow, unknown>,
    {
      accessorKey: "approvedByName",
      header: () => <ColumnHeader tKey="approvedBy" ns="inventory" />,
      cell: ({ row }) => row.original.approvedByName || "—",
    } as ColumnDef<StockMovementRow, unknown>,
    {
      // When the item was entered — the date only, no time of day (the
      // admin's request, 2026-10-22).
      accessorKey: "createdAt",
      header: () => <ColumnHeader tKey="date" ns="inventory" />,
      cell: ({ row }) => <span className="whitespace-nowrap">{formatDate(row.original.createdAt)}</span>,
    } as ColumnDef<StockMovementRow, unknown>,
    ]),
  ]
  if (onApprove && onReject && onMap) {
    columns.push({
      id: "approve",
      header: "",
      cell: ({ row }) => <ApprovalActionsCell movement={row.original} onApprove={onApprove} onReject={onReject} onMap={onMap} />,
    })
  }
  if (onEdit) {
    columns.push({
      id: "edit",
      header: "",
      // A row combining several movements (mergedIds) opens the grouped edit
      // form, which edits each combined entry (StockMovementFormDialog).
      cell: ({ row }) => <EditButtonCell movement={row.original} onEdit={onEdit} />,
    })
  }
  return columns
}

// The Inventory List shows one row per item per job: several movements a job
// queued for the same item (e.g. a repair with two part rows for 012, or a
// schedule job's recorded filter items) are combined into a single row with
// the total quantity. Only merges trigger-created job movements that agree
// on job, item, direction, reason and status — a manual entry, or two jobs,
// are never combined. Display only: the stored movements stay one per
// recorded part/item, so each still links back to what created it.
export function groupInventoryListRows(rows: StockMovementRow[]): StockMovementRow[] {
  const out: StockMovementRow[] = []
  const byKey = new Map<string, StockMovementRow>()
  for (const r of rows) {
    const job = r.filterChangePlanId ?? r.installPlanId ?? r.scheduleJobId ?? (r.repairPlanPartId ? `rep:${r.relatedJobOrderNo ?? r.referenceNumber}` : undefined)
    if (!job) {
      out.push(r)
      continue
    }
    const direction = directionOf(r)
    // A requested edit/delete is never combined with another movement.
    if (r.changeRequest) {
      out.push(r)
      continue
    }
    const key = [job, r.productId || r.itemLabel, direction, r.reason, r.status, r.slipType ?? ""].join("|")
    const existing = byKey.get(key)
    if (!existing) {
      const copy = { ...r, mergedIds: [r.id] }
      byKey.set(key, copy)
      out.push(copy)
      continue
    }
    existing.quantityAdded += r.quantityAdded
    existing.quantityRemoved += r.quantityRemoved
    existing.secondHandReadyQuantity = (existing.secondHandReadyQuantity || 0) + (r.secondHandReadyQuantity || 0)
    existing.secondHandRepairQuantity = (existing.secondHandRepairQuantity || 0) + (r.secondHandRepairQuantity || 0)
    existing.demoQuantity = (existing.demoQuantity || 0) + (r.demoQuantity || 0)
    existing.mergedIds = [...(existing.mergedIds ?? [existing.id]), r.id]
    if (r.createdAt > existing.createdAt) existing.createdAt = r.createdAt
  }
  return out
}

// The Inventory List modal's per-item totals: every row for the same item
// moving the same way with the same status is combined into one, across
// jobs — e.g. three 012 Pre-Carbon filters used on three visits become one
// "-3" row whose Related Job lists all three orders. Pending and approved
// rows are never combined (a total must be all one or the other), nor IN
// with OUT. Reason, Created By and Approved By list each distinct value.
export function aggregateInventoryRowsByItem(rows: StockMovementRow[]): StockMovementRow[] {
  const out: StockMovementRow[] = []
  const byKey = new Map<string, StockMovementRow>()
  const joinDistinct = (a: string | undefined, b: string | undefined) => {
    const parts = [...new Set([...(a ?? "").split(", "), ...(b ?? "").split(", ")].map((x) => x.trim()).filter(Boolean))]
    return parts.length > 0 ? parts.join(", ") : undefined
  }
  for (const r of rows) {
    const direction = directionOf(r)
    const key = [r.productId || `label:${r.itemLabel}`, direction, r.status, r.changeRequest ? `req:${r.id}` : "", r.slipType ?? ""].join("|")
    const existing = byKey.get(key)
    if (!existing) {
      const copy = { ...r, mergedIds: r.mergedIds ?? [r.id] }
      byKey.set(key, copy)
      out.push(copy)
      continue
    }
    existing.quantityAdded += r.quantityAdded
    existing.quantityRemoved += r.quantityRemoved
    existing.secondHandReadyQuantity = (existing.secondHandReadyQuantity || 0) + (r.secondHandReadyQuantity || 0)
    existing.secondHandRepairQuantity = (existing.secondHandRepairQuantity || 0) + (r.secondHandRepairQuantity || 0)
    existing.demoQuantity = (existing.demoQuantity || 0) + (r.demoQuantity || 0)
    existing.mergedIds = [...(existing.mergedIds ?? [existing.id]), ...(r.mergedIds ?? [r.id])]
    existing.relatedJobOrderNo = joinDistinct(existing.relatedJobOrderNo, r.relatedJobOrderNo)
    existing.reason = (joinDistinct(existing.reason, r.reason) ?? existing.reason) as StockMovementRow["reason"]
    existing.userName = joinDistinct(existing.userName, r.userName) ?? existing.userName
    existing.approvedByName = joinDistinct(existing.approvedByName, r.approvedByName)
    if (r.createdAt > existing.createdAt) existing.createdAt = r.createdAt
  }
  return out
}

